export function getWilayaByCode(code: string): WilayaData | undefined {
  return ALGERIAN_WILAYAS_69.find((w) => w.code === code || w.name.startsWith(code));
}

export function searchWilaya(query: string): WilayaData[] {
  if (!query) return ALGERIAN_WILAYAS_69;
  const q = query.toLowerCase().trim();
  return ALGERIAN_WILAYAS_69.filter(
    (w) =>
      w.name.toLowerCase().includes(q) ||
      w.rawName.toLowerCase().includes(q) ||
      w.latinName.toLowerCase().includes(q) ||
      w.code.includes(q)
  );
}
